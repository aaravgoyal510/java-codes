public class AssignmentOperations
{
	
	public static void main(String args[])
	{
	    System.out.println("Made by Aarav Goyal ERP 0251BCA116");

		int x=10;
		System.out.println("The value of x is "+x); //print 10
	
		//Compound Assignment Operation
	
		x+=10;
		System.out.println("The value of x is "+x); //print 20
	
		x-=5;
		System.out.println("The value of x is "+x); //print 15
	
		x*=2;
		System.out.println("The value of x is "+x); //print 30
	
		x/=4;
		System.out.println("The value of x is "+x); //print 7
	
		x%=4;
		System.out.println("The value of x is "+x); //print 3
	}
}
